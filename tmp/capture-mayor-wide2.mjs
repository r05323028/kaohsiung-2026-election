import { chromium } from '@playwright/test';
const browser = await chromium.launch({ headless:true, args:['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport:{width:1600,height:1000}, reducedMotion:'reduce' });
const page = await context.newPage();
await page.goto('http://127.0.0.1:4321/?district=kaohsiung-mayor-2026&candidate=zhang-jing-2026', {waitUntil:'domcontentloaded'});
await page.locator('[data-testid="city-explorer"][data-hydrated="true"]').waitFor({timeout:30000});
await page.locator('canvas').waitFor({timeout:30000});
await page.waitForFunction(() => Boolean(window.__kaohsiungWorld), undefined, {timeout:30000});
await page.waitForTimeout(2500);
const before = await page.evaluate(() => ({focus: document.querySelector('[data-testid="city-explorer"]')?.getAttribute('data-scene-focus'), dpr: devicePixelRatio}));
console.log('before', JSON.stringify(before));
await page.evaluate(() => window.__kaohsiungWorld?.advance(900));
await page.waitForTimeout(12000);
await page.screenshot({path:'tmp/mayor-follow-wide2.png', timeout:120000});
const after = await page.evaluate(() => ({focus: document.querySelector('[data-testid="city-explorer"]')?.getAttribute('data-scene-focus'), stats: window.__kaohsiungWorld?.stats()}));
console.log('after', JSON.stringify(after));
await browser.close();
