import { chromium } from 'playwright';
const BASE = 'http://127.0.0.1:4321';
const out = process.argv[2] ?? 'tmp/park-1.png';
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 1 });
await page.goto(BASE + '/?focus=metropolitan-park', { waitUntil: 'networkidle' });
await page.locator('[data-testid="city-explorer"][data-hydrated="true"]').waitFor({ timeout: 30000 });
await page.locator('canvas').waitFor({ timeout: 30000 });
await page.waitForTimeout(6000);
await page.screenshot({ path: out });
console.log(JSON.stringify({ camera: await page.evaluate(() => window.__kaohsiungWorld?.camera?.() ?? null), focus: await page.locator('[data-testid="city-explorer"]').getAttribute('data-scene-focus') }));
await browser.close();
