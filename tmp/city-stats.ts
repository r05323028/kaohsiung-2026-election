import { buildTrees, buildLotus, buildStaticCity, buildLandmarks } from '../src/city/layout';
import { MATERIALS } from '../src/city/materials';
const trees = buildTrees();
const byKind: Record<string, number> = {};
for (const t of trees) byKind[t.kind] = (byKind[t.kind] ?? 0) + 1;
const lotus = buildLotus();
const city = buildStaticCity('high');
const landmarks = buildLandmarks('high');
let triangles = 0;
const count = (g: any) => (g.index ? g.index.count : (g.getAttribute('position')?.count ?? 0)) / 3;
for (const part of city) triangles += count(part.geometry);
for (const lm of landmarks) for (const part of lm.parts) triangles += count(part.geometry);
console.log(JSON.stringify({materials: Object.keys(MATERIALS).length, treeTotal: trees.length, byKind, lotusLeaves: lotus.leaves.length, lotusFlowers: lotus.flowers.length, staticParts: city.length, landmarkGroups: landmarks.length, landmarkParts: landmarks.reduce((n,l)=>n+l.parts.length,0), staticTriangles: Math.round(triangles)}, null, 2));
