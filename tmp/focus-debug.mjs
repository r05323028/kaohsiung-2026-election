import { chromium } from 'playwright';
const browser = await chromium.launch({headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1280,height:900}});
await page.goto('http://127.0.0.1:4321/');
await page.waitForSelector('[data-testid="city-explorer"][data-hydrated="true"]');
const active = async (label) => console.log(label, await page.evaluate(() => ({tag: document.activeElement?.tagName, cls: document.activeElement?.className, label: document.activeElement?.getAttribute('aria-label'), text: document.activeElement?.textContent?.slice(0,40)})));
await active('initial');
await page.locator('[aria-controls="city-people-tray"]').click();
await active('after open tray');
await page.getByRole('button',{name:/林海星/}).first().click();
await page.waitForTimeout(900);
await active('after select');
await page.keyboard.press('Escape');
await page.waitForTimeout(120);
await active('after esc 120ms');
await page.waitForTimeout(600);
await active('after esc 720ms');
console.log('panel', await page.locator('.profile-panel.is-open').count());
await browser.close();
