import { chromium } from '@playwright/test';
const browser = await chromium.launch({ headless: true, args:['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport:{width:1600,height:1000}, reducedMotion:'reduce' });
const page = await context.newPage();
await page.goto('http://127.0.0.1:4321/?district=kaohsiung-mayor-2026&candidate=zhang-jing-2026', { waitUntil:'domcontentloaded' });
await page.locator('[data-testid="city-explorer"][data-hydrated="true"]').waitFor({timeout:30000});
await page.locator('canvas').waitFor({timeout:30000});
await page.waitForTimeout(2500);
const info = await page.evaluate(() => ({ zoom: document.body.dataset.cameraZoom, target: document.body.dataset.cameraTarget, follow: document.body.dataset.cameraFollow, focus: document.querySelector('[data-testid="city-explorer"]')?.getAttribute('data-scene-focus') }));
const actor = await page.evaluate(() => { const w = window.__kaohsiungWorld; const a = w?.actors().find(a=>a.slug==='zhang-jing-2026'); return a ? {pos:a.position, district:a.currentAdminName, state:a.state} : null; });
console.log(JSON.stringify({info, actor}));
await browser.close();
