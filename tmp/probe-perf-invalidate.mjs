import { chromium } from '@playwright/test';
const browser = await chromium.launch({ headless: true, args:['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport:{width:1600,height:1000}, reducedMotion:'reduce' });
const page = await context.newPage();
page.on('pageerror', e=>console.log('PAGEERROR', e.message));
page.on('console', m=>{ if(m.type()==='error') console.log('CONSOLE', m.text().slice(0,500)); });
await page.goto('http://127.0.0.1:4321/?district=kaohsiung-mayor-2026&candidate=zhang-jing-2026&perf=1', { waitUntil:'domcontentloaded' });
await page.locator('[data-testid="city-explorer"][data-hydrated="true"]').waitFor({timeout:30000});
await page.locator('canvas').waitFor({timeout:30000});
await page.waitForTimeout(5000);
console.log('before', await page.evaluate(()=>JSON.stringify(window.__cityDiagnostics)));
await page.evaluate(()=>window.__r3fState?.invalidate?.());
await page.waitForTimeout(2500);
console.log('after', await page.evaluate(()=>JSON.stringify(window.__cityDiagnostics)));
await page.screenshot({path:'tmp/perf-after-invalidate.png', timeout:120000});
await browser.close();
