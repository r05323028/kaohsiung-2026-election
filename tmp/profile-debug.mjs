import { chromium } from 'playwright';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
page.on('console', (m) => console.log('console', m.type(), m.text()));
page.on('pageerror', (e) => console.log('pageerror', e.message));
page.on('requestfailed', (r) => console.log('failed', r.url(), r.failure()?.errorText));
await page.goto('http://127.0.0.1:4321/', { waitUntil: 'domcontentloaded' });
await page.waitForSelector('[data-testid="city-explorer"][data-hydrated="true"]');
await page.getByLabel('搜尋人物').fill('林海星');
await page.waitForTimeout(800);
await page.getByRole('button', { name: /林海星/ }).first().click();
await page.waitForTimeout(2500);
console.log('panel text:', (await page.getByTestId('profile-panel').innerText()).slice(0,200));
console.log('tabs', await page.getByTestId('profile-panel').getByRole('tab').count());
await browser.close();
