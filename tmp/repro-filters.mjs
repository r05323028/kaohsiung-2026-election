import { chromium } from '@playwright/test';
const browser = await chromium.launch({ args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, reducedMotion: 'reduce' });
const page = await context.newPage();
page.on('console', m => console.log('console', m.type(), m.text().slice(0,100)));
await page.goto('http://127.0.0.1:4321/', { waitUntil: 'domcontentloaded' });
await page.waitForSelector('[data-testid="city-explorer"][data-hydrated="true"]');
console.log('hydrated');
const explorer = page.getByTestId('city-explorer');
await explorer.locator('[aria-controls="city-district-tray"]').click();
console.log('tray open');
await explorer.getByRole('tab', { name: '市長選' }).click();
console.log('mayor tab');
await explorer.locator('#city-district-tray').getByRole('button', { name: /高雄市長選舉/ }).click();
console.log('mayor district');
await explorer.getByRole('tab', { name: '市議選' }).click();
console.log('council tab');
const councilDistrict = explorer.locator('#city-district-tray').getByRole('button', { name: /高雄市議員第1選舉區/ });
await councilDistrict.click();
console.log('council district');
await explorer.locator('[aria-controls="city-people-tray"]').click();
console.log('people open');
const names = await explorer.locator('#city-people-tray').getByRole('button').allTextContents();
console.log(names.slice(0,5));
console.log('scene', await page.locator('#scene-heading').textContent());
await browser.close();
